def sha(b):
    return hashlib.sha256(b).hexdigest().upper()


def ok(l, d=""):
    print(f"  [OK] {l}" + (f"  {d}" if d else ""))


def rep(t, old, new, label):
    n = t.count(old)
    if n != 1:
        raise SystemExit(f"[ABORT] {label}: 期望 1 次，实际 {n}")
    ok(label)
    return t.replace(old, new, 1)


def actions(t):
    return set(re.findall(r'data-a="([a-z0-9-]+)"', t))


