#!/usr/bin/env python3
"""Pixel captures from both running HTML versions, same fixture, viewport and theme.
Only the optional --offline-dom mode replaces Storage for local visual iteration.
Release evidence is generated by the default real HTTP/localStorage mode in CI.
"""
from pathlib import Path
import sys,json,hashlib,shutil
from urllib.parse import quote
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
# Reuse the accepted isolated fixture and action helpers, not the old test runner.
p=ROOT/'tests/v978_browser.py';helpers={'__file__':str(p),'__name__':'fixtures'}
exec(compile(p.read_text().split('with sync_playwright() as pw:')[0],str(p),'exec'),helpers)
offline=helpers['OFFLINE'];OUT=ROOT/('artifacts/v980/visual-render' if offline else 'artifacts/v980/visual');OUT.mkdir(parents=True,exist_ok=True)
origin=helpers['URL'].rsplit('/',1)[0];checks=[];metrics=[];pairs=[];errors=[]
def ck(ok,name,data=None):
 checks.append({'name':name,'pass':bool(ok),'detail':data})
 if not ok:raise AssertionError(name+' '+str(data))
def click(p,q):helpers['click'](p,q)
def home(p):helpers['home'](p)
def facility(p,q):helpers['facility'](p,q)
def state(p):return helpers['state'](p)
def configure(version):
 rel='releases/山野修仙记_V90.79_纸墨精修.html' if version=='before' else 'index.html'
 helpers['HTML']=(ROOT/rel).read_text();helpers['URL']=origin+'/'+quote(rel)
 return hashlib.sha256((ROOT/rel).read_bytes()).hexdigest().upper()
def prepare(p,scenario):
 helpers['seed'](p,mature=scenario=='garden-ready');home(p)
 if scenario=='home':return
 facility(p,{'forge':'facility-forge','alchemy':'facility-alchemy','workbench':'facility-workbench','spirit':'facility-spirit'}.get(scenario,'garden'))
 if scenario=='alchemy':click(p,'[data-a="facility-tab"][data-tab="food"]')
 if scenario=='workbench':
  click(p,'[data-a="facility-tab"][data-tab="bag"]');p.locator('#facility-tier').select_option('12')
 if scenario in ['garden-growing','garden-sow']:
  click(p,'[data-a="garden-plot"][data-index="0"]');p.locator('#garden-seed').select_option('seedHerb')
  if scenario=='garden-growing':click(p,'[data-a="garden-confirm"]')
def snap(p,name):
 p.wait_for_function('!document.querySelector("#toast.show")',timeout=15000);p.screenshot(path=str(OUT/(name+'.png')))
def bounds(p,w,h,name,fit=False):
 m=p.locator('#panel-body').evaluate('e=>({width:e.clientWidth,scrollWidth:e.scrollWidth,height:e.clientHeight,scrollHeight:e.scrollHeight})');metrics.append(dict(viewport=[w,h],screen=name,**m))
 ck(m['scrollWidth']<=m['width']+1,'no horizontal overflow '+name+str((w,h)),m)
 if fit:ck(m['scrollHeight']<=m['height']+2,'single-screen content '+name+str((w,h)),m)
 close=p.locator('.panel-close').bounding_box();ck(close and close['x']>=0 and close['y']>=0 and close['x']+close['width']<=w+1 and close['y']+close['height']<=h+1,'close reachable '+name)
names={'home':'01_洞府','forge':'02_炼器室','alchemy':'03_丹房','workbench':'04_工作台','spirit':'05_赋灵','garden':'06_灵田','garden-growing':'07_生长','garden-ready':'08_成熟','garden-sow':'09_播种确认'}
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path=shutil.which('chromium'),headless=True,args=['--no-sandbox','--disable-dev-shm-usage']);ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True);p=ctx.new_page();p.set_default_timeout(7000);p.on('pageerror',lambda e:errors.append(str(e)))
 try:
  for scenario,label in names.items():
   ss=[];sigs=[]
   for version in ['before','after']:
    digest=configure(version);prepare(p,scenario);p.evaluate("applyVisualTheme('forest',false)");snapshot=state(p);snap(p,label+'_'+version)
    ck(state(p)==snapshot,'taking screenshot does not mutate game '+scenario+version)
    payload=json.dumps(snapshot,ensure_ascii=False,sort_keys=True).encode();sig=hashlib.sha256(payload).hexdigest();ss.append(snapshot);sigs.append(sig)
    if version=='after':
     bounds(p,390,844,scenario,scenario in ['home','garden','garden-growing','garden-ready'])
     corners=p.evaluate('''()=>{const selectors=['#phone','.panel-close','.btn','.ui979-tier','.ui979-seal','.ui979-facility','.ui979-recipe','.garden978-plot','.facility978-tabs','.home978-nav','.garden978-modal'];return Object.fromEntries(selectors.map(s=>{const e=document.querySelector(s);return [s,e?getComputedStyle(e).borderTopLeftRadius:null]}))}''')
     ck(all(v in [None,'0px'] for v in corners.values()),'real CSS has only square corners '+scenario,corners)

   ck(ss[0]==ss[1],'same player data before/after '+scenario)
   pairs.append(dict(scenario=scenario,before=label+'_before.png',after=label+'_after.png',stateSha256=sigs[0],sameState=sigs[0]==sigs[1]))
  configure('after')
  for w,h in [(320,568),(360,640),(390,844),(430,932),(768,1024),(1280,900)]:
   p.set_viewport_size(dict(width=w,height=h))
   for scenario in ['home','workbench','garden']:
    prepare(p,scenario);bounds(p,w,h,scenario,scenario in ['home','garden']);snap(p,f'{w}x{h}_{scenario}')
   click(p,'[data-a="garden-plot"][data-index="0"]');mb=p.locator('.garden978-modal').bounding_box();ck(mb['y']>=0 and mb['y']+mb['height']<=h+1,'sow modal inside viewport '+str((w,h)),mb);snap(p,f'{w}x{h}_sow')
  p.set_viewport_size(dict(width=390,height=844))
  for theme in ['mono','immortal']:
   for scenario in ['home','workbench','garden']:
    prepare(p,scenario);p.evaluate('v=>applyVisualTheme(v,false)',theme);snap(p,f'{theme}_{scenario}');bounds(p,390,844,theme+scenario,scenario in ['home','garden'])
  # Full-grid plot index retention is covered by V90.79 and the 27-suite engine regression.
  ck(not errors,'no browser runtime exceptions',errors)
 except Exception:
  p.screenshot(path=str(OUT/'FAILURE.png'));raise
 finally:
  report=dict(version='V90.80',mode='offline-dom-storage-shim' if offline else 'native-http-localStorage',sourceSha256=hashlib.sha256((ROOT/'index.html').read_bytes()).hexdigest().upper(),baselineSha256=hashlib.sha256((ROOT/'releases/山野修仙记_V90.79_纸墨精修.html').read_bytes()).hexdigest().upper(),checks=checks,passed=sum(x['pass'] for x in checks),total=len(checks),pairs=pairs,metrics=metrics,errors=errors,screenshots=sorted(x.name for x in OUT.glob('*.png')))
  (OUT/'results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2));ctx.close();b.close();helpers['server'].shutdown()
print('V90.80 VISUAL PASS',report['passed'],'/',report['total'],report['mode'])
